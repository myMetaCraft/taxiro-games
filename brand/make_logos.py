"""Generates the Taxiro logo variants (original designs). Wordmark glyphs are outlined from
Space Grotesk (SIL OFL 1.1, see assets/fonts/LICENSE-SpaceGrotesk.txt) so SVGs need no font."""
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
import os
HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.join(HERE, '..', 'assets', 'fonts', 'space-grotesk.woff2')

def word_paths(word, wght, size, tracking_em, skew=0.0):
    f = instantiateVariableFont(TTFont(FONT), {'wght': wght})
    gs = f.getGlyphSet(); cmap = f.getBestCmap(); upm = f['head'].unitsPerEm
    capH = f['OS/2'].sCapHeight; s = size / upm; x = 0; out = []
    for ch in word:
        gn = cmap[ord(ch)]
        pen = SVGPathPen(gs)
        # y flipped, baseline at capH; optional skew (italic slant)
        gs[gn].draw(TransformPen(pen, (s, 0, skew * s, -s, x * s, capH * s)))
        out.append((ch, pen.getCommands()))
        x += f['hmtx'][gn][0] + tracking_em * upm
    return out, (x - tracking_em * upm) * s, capH * s

