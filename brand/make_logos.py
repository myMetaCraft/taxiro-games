def build(name, v):
    w = v['word']
    paths, ww, wh = word_paths(w['text'], w['wght'], w['size'], w['tracking'], w.get('skew', 0))
    gap = 18; ox = 56 + gap; oy = (56 - wh) / 2
    W = round(ox + ww + w.get('skew', 0) * wh + 2, 2)
    glyphs = '\n    '.join(f'<path d="{d}" fill="{w["accent"].get(ch, w["fill"])}"/>' for ch, d in paths)
    note = '<!-- Taxiro logo ' + name + ' — original design, generated by brand/make_logos.py -->'
    full = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} 56" width="{W}" height="56" role="img" aria-label="Taxiro">
  {note}
  <title>Taxiro</title>
  <defs>
    {v['defs']}
  </defs>
  {v['mark']}
  <g transform="translate({ox} {oy:.2f})">
    {glyphs}
  </g>
</svg>
'''
    icon = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 56 56" width="56" height="56" role="img" aria-label="Taxiro">
  {note}
  <defs>
    {v['defs']}
  </defs>
  {v['mark']}
</svg>
'''
    # wordmark only
    word = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {round(ww + w.get('skew',0)*wh + 2,2)} {wh:.2f}" role="img" aria-label="Taxiro">
  {note}
  <defs>
    {v['defs']}
  </defs>
  {glyphs}
</svg>
'''
    for suffix, svg in (('', full), ('_icon', icon), ('_wordmark', word)):
        open(os.path.join(HERE, f'logo_{name}{suffix}.svg'), 'w').write(svg)

for k, v in V.items():
    build(k, v)
